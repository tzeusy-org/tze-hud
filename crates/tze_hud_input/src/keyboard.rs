//! Native keyboard event types used by shell, command and composer routing.
//!
//! Raw key and post-IME character events carry local timestamps and modifiers.
//! The runtime owns routing and editing; there is no resident keyboard feed.

use serde::{Deserialize, Serialize};
use tze_hud_scene::MonoUs;

// ─── Modifier flags ────────────────────────────────────────────────────────────

/// Keyboard modifier state carried by key events.
///
/// Represented as a struct of boolean flags.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct KeyboardModifiers {
    pub shift: bool,
    pub ctrl: bool,
    pub alt: bool,
    pub meta: bool,
    /// CapsLock toggle state (not a momentary modifier).
    pub caps_lock: bool,
    /// NumLock toggle state.
    pub num_lock: bool,
}

impl KeyboardModifiers {
    /// No modifiers active.
    pub const NONE: Self = Self {
        shift: false,
        ctrl: false,
        alt: false,
        meta: false,
        caps_lock: false,
        num_lock: false,
    };
}

// ─── Raw OS keyboard event ─────────────────────────────────────────────────────

/// Raw key-down event from the OS (before focus routing).
///
/// `key_code` is the DOM `KeyboardEvent.code` string (physical key position,
/// e.g. `"KeyA"`, `"ArrowDown"`, `"ShiftLeft"`).
/// `key` is the DOM `KeyboardEvent.key` string (logical value after layout +
/// modifiers, e.g. `"a"`, `"A"`, `"ArrowDown"`).
///
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct RawKeyDownEvent {
    /// Physical key position (DOM `KeyboardEvent.code`).
    pub key_code: String,
    /// Logical key value (DOM `KeyboardEvent.key`).
    pub key: String,
    /// Active modifiers at the time of the event.
    pub modifiers: KeyboardModifiers,
    /// True if this event was generated by the OS key-repeat mechanism.
    pub repeat: bool,
    /// Monotonic timestamp in microseconds (hardware timestamp from winit).
    pub timestamp_mono_us: MonoUs,
}

/// Raw key-up event from the OS.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct RawKeyUpEvent {
    pub key_code: String,
    pub key: String,
    pub modifiers: KeyboardModifiers,
    pub timestamp_mono_us: MonoUs,
}

/// Post-IME character event — committed Unicode text ready for insertion.
///
/// In v1 this is produced directly from OS character events when no IME is
/// active. Each event carries exactly the characters the OS committed (usually
/// a single codepoint, occasionally a multi-character string for ligatures /
/// precomposed sequences).
///
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct RawCharacterEvent {
    /// Post-IME committed Unicode character(s).
    pub character: String,
    pub timestamp_mono_us: MonoUs,
}
